"""Generate evals/cases.yaml from evals/oracle.py's output.

Expected values come straight from the independent oracle (run as a subprocess,
so no oracle code is imported here). Question text, tolerances and xfail flags
come from specs/eval_spec.md, encoded below.

Run: python scripts/gen_cases.py
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ORACLE = ROOT / "evals" / "oracle.py"
OUT = ROOT / "evals" / "cases.yaml"

# Metadata per specs/eval_spec.md (expected is filled from the oracle).
META = {
    "E01": {"metric": "revenue",
            "question": "What was our total recognized revenue in USD for paid invoices in 2024?",
            "tolerance": {"type": "relative", "value": 0.005}, "xfail": False},
    "E02": {"metric": "mrr",
            "question": "Which region has the highest average MRR per account?",
            "tolerance": {"type": "relative", "value": 0.01}, "xfail": False},
    "E03": {"metric": "churn",
            "question": "What is the churn rate among Enterprise accounts?",
            "tolerance": {"type": "absolute", "value": 0.01}, "xfail": False,
            "answer_key": "churn_rate"},
    "E04": {"metric": "revenue",
            "question": "How much have we given back in refunds?",
            "tolerance": {"type": "absolute", "value": 0.01}, "xfail": False},
    "E05": {"metric": "churn",
            "question": "What was our monthly churn rate in 2024?",
            "tolerance": {"type": "absolute", "value": 0}, "xfail": True},
}


def q(s: str) -> str:
    return '"' + s.replace('"', '\\"') + '"'


def main() -> int:
    proc = subprocess.run([sys.executable, str(ORACLE)], capture_output=True, text=True)
    if proc.returncode != 0:
        print(f"oracle failed:\n{proc.stderr}", file=sys.stderr)
        return 1
    expected = json.loads(proc.stdout)

    lines = [
        "# GENERATED by scripts/gen_cases.py from evals/oracle.py — do not hand-edit.",
        "# Expected values are the independent oracle's; metadata from specs/eval_spec.md.",
        "cases:",
    ]
    for cid, meta in META.items():
        exp = expected.get(cid)
        lines += [
            f"  - id: {cid}",
            f"    metric: {meta['metric']}",
            f"    question: {q(meta['question'])}",
            f"    expected: {'null' if exp is None else exp}",
            f"    tolerance: {{type: {meta['tolerance']['type']}, value: {meta['tolerance']['value']}}}",
            f"    xfail: {str(meta['xfail']).lower()}",
        ]
        if meta.get("answer_key"):
            lines.append(f"    answer_key: {meta['answer_key']}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT} ({len(META)} cases). Expected: {expected}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
